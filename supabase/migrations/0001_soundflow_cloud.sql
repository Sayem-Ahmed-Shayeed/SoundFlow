-- Soundflow cloud accounts and transcript sync.
-- Run once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Safe to re-run: every statement is idempotent.

-- ---------------------------------------------------------------------------
-- Profiles: one row per auth user, created automatically on sign-up.
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
    id          uuid primary key references auth.users (id) on delete cascade,
    full_name   text not null default '',
    gender      text check (gender in ('male', 'female')),
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
    for select to authenticated using ((select auth.uid()) = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles
    for insert to authenticated with check ((select auth.uid()) = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles
    for update to authenticated
    using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

-- Copy name/gender from sign-up metadata (email sign-up sends both; Google
-- provides full_name/name only, and the app asks for gender afterwards).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
    g text := lower(coalesce(meta ->> 'gender', ''));
begin
    insert into public.profiles (id, full_name, gender)
    values (
        new.id,
        coalesce(nullif(meta ->> 'full_name', ''), nullif(meta ->> 'name', ''), ''),
        case when g in ('male', 'female') then g else null end
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- Transcripts: id is generated by the desktop client so uploads are
-- idempotent. Deletes are soft (deleted_at) so other devices learn about them.
-- ---------------------------------------------------------------------------
create table if not exists public.transcripts (
    id          uuid primary key,
    user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    duration_s  real not null default 0,
    title       text not null default '',
    summary     text not null default '',
    body        text not null default '',
    deleted_at  timestamptz
);

create index if not exists transcripts_user_updated_idx
    on public.transcripts (user_id, updated_at);

alter table public.transcripts enable row level security;

drop policy if exists "transcripts_select_own" on public.transcripts;
create policy "transcripts_select_own" on public.transcripts
    for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "transcripts_insert_own" on public.transcripts;
create policy "transcripts_insert_own" on public.transcripts
    for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "transcripts_update_own" on public.transcripts;
create policy "transcripts_update_own" on public.transcripts
    for update to authenticated
    using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

drop policy if exists "transcripts_delete_own" on public.transcripts;
create policy "transcripts_delete_own" on public.transcripts
    for delete to authenticated using ((select auth.uid()) = user_id);

-- Server clock owns updated_at so clients can pull "changed since" reliably.
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := clock_timestamp();
    return new;
end;
$$;

drop trigger if exists transcripts_touch_updated_at on public.transcripts;
create trigger transcripts_touch_updated_at
    before insert or update on public.transcripts
    for each row execute function public.touch_updated_at();

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
    before update on public.profiles
    for each row execute function public.touch_updated_at();
